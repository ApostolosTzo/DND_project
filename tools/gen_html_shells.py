BODY_TAIL = """\
</body>
</html>"""

# The PWA's behaviour lives in js/*.js - loaded before the adapter, which
# wraps them behind the Backend seam.
PWA_SCRIPTS = "".join(
    '    <script src="js/%s.js"></script>\n' % name
    for name in ("dice", "game_data", "items", "enemy", "player",
                 "quests", "shop", "world_map", "saves", "game"))


def read(path):
    with io.open(path, encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n").rstrip("\n")


def inline_script(source_text, source_name):
    """Wrap a source file in an inline <script> block, refusing to ship a
    shell that HTML would cut in half at the first literal </script>."""
    assert "</script" not in source_text.lower(), "%s contains </script" % source_name
    return "<script>\n%s\n</script>\n" % source_text


def build_shell(head, adapter_file, adapter_source, shared_source, css):
    assert "</style" not in css.lower(), "codex.css contains </style"
    style = "<style>\n%s\n</style>\n" % css
    adapter_block = inline_script(adapter_source, adapter_file)
    shared_block = inline_script(shared_source, "shared_page.js")
    return (GENERATED_NOTE.format(adapter=adapter_file)
            + head + style + BODY_HEAD
            + (PWA_SCRIPTS if head is PWA_HEAD else "")
            + adapter_block + shared_block + BODY_TAIL)


def main(argv):
    css = read(os.path.join(SHELLS, "codex.css"))
    shared = read(os.path.join(SHELLS, "shared_page.js"))
    pwa_adapter = read(os.path.join(SHELLS, "pwa_adapter.js"))
    flask_adapter = read(os.path.join(SHELLS, "flask_adapter.js"))

    targets = [
        (os.path.join(ROOT, "index.html"),
         build_shell(PWA_HEAD, "pwa_adapter.js", pwa_adapter, shared, css)),
        (os.path.join(ROOT, "templates", "index.html"),
         build_shell(FLASK_HEAD, "flask_adapter.js", flask_adapter, shared, css)),
    ]

    if "--check" in argv:
        stale = []
        for path, content in targets:
            try:
                current = read(path)
            except IOError:
                current = None
            if current != content:
                stale.append(os.path.relpath(path, ROOT).replace(os.sep, "/"))
        if stale:
            print("STALE shells: %s" % ", ".join(stale))
            print("run: py tools/gen_html_shells.py")
            return 1
        print("shells are up to date")
        return 0

    for path, content in targets:
        with io.open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content + "\n")
        print("wrote %s (%d bytes)" % (
            os.path.relpath(path, ROOT).replace(os.sep, "/"),
            len((content + "\n").encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

#!/usr/bin/env py
# -*- coding: utf-8 -*-
"""Assemble both UI shells from their sources.

One design, one page script, two builds:

    tools/shells/codex.css        the design (both builds share it verbatim)
    tools/shells/shared_page.js   the render/navigation script
    tools/shells/pwa_adapter.js   Backend seam for the static PWA
    tools/shells/flask_adapter.js Backend seam for the Flask build

The sources are embedded inline (styles and scripts, exactly as the shells
always carried them) so the precached index.html stays self-contained and the
PWA keeps working offline: sw.js precaches index.html, and an external
stylesheet request with no network would break first paint.

Usage:
    py tools/gen_html_shells.py           # rewrite both shells
    py tools/gen_html_shells.py --check   # exit 1 if either shell is stale
"""

import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHELLS = os.path.join(ROOT, "tools", "shells")

GENERATED_NOTE = (
    "<!-- GENERATED by tools/gen_html_shells.py - do not edit here.\n"
    "     Sources: tools/shells/codex.css, tools/shells/shared_page.js,\n"
    "     tools/shells/{adapter}. Edit those and regenerate. -->"
)

